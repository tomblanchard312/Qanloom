pub(crate) fn paint(p: &Painter, r: Rect, name: &str, ink: Color32, accent: Color32, selected: bool) {
    if name == "assistant" || name.starts_with("shape.") {
        super::paint(p, r, name, ink, accent);
        return;
    }
    let glyph = glyph_for(name).unwrap_or(glyph::COMMAND);
    let family = if selected { fonts::icons_fill() } else { fonts::icons() };
    let font = FontId::new(r.width().min(r.height()), family);
    // Shared widgets can draw before the app installs its named font families.
    if p.ctx().fonts_mut(|f| f.has_glyphs(&font, glyph)) {
        p.text(r.center(), Align2::CENTER_CENTER, glyph, font, ink);
    } else {
        super::paint(p, r, name, ink, accent);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn regular_and_selected_ribbon_faces_cover_commands_and_the_eridu_supplement() {
        let ctx = egui::Context::default();
        crate::theme::install_fonts(&ctx);
        ctx.run_ui(egui::RawInput::default(), |ui| {
            for family in [fonts::icons(), fonts::icons_fill()] {
                let font = FontId::new(17.0, family);
                for name in ["paste", "bold", "insertAbove", "trackChanges", "margins", "pageBreak", "footnote", "editor"] {
                    let glyph = glyph_for(name).unwrap();
                    assert!(ui.fonts_mut(|f| f.has_glyphs(&font, glyph)), "{name}: missing glyph");
                }
            }
        })
        .drop_without_applying_deltas();
    }
}
